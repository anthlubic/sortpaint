"""The hand-authored level pictures, one character per cell.

A sprite is a square block of characters. A '.' is a hole (the game draws nothing there) and every
other character is a key into PALETTE, which becomes one sphere colour. scripts/make_level_sprites.py
renders these to PNGs; scripts/import_level.py is what decides whether a rendered one is a level.

New art is 24x24. The first six pictures are still 16x16 and are due a redraw; nothing in the game
cares (src/BoardView.cs fits whatever grid the PNG describes), so the two sizes coexist until then.

Three rules bound what can be drawn here, all of them enforced downstream:

  * more than 24 filled cells, so the picture outlasts a tray
  * two to eight colours
  * no colour on more than half the filled cells, or the scramble cannot avoid leaving some cell
    already sitting on its target

The last one is the one that bites. A big single-colour body wants an outline, shading, or a
second material to split it, and `make_level_sprites.py` prints the share of every sprite it draws.
"""

# A shadow colour may not simply be its hero darkened. shaders/sphere.gdshader lights every bead
# from `ambient` (0.45) up to full brightness, so one bead already covers more than twice its own
# lightness: the lit side of a dark bead lands on the shaded side of a light one. Lightness is
# spent on the lighting, which leaves hue and chroma as the only cue telling two colours apart.
# Every hero/shadow pair below is therefore rotated in hue as well as darkened, and the pairs that
# share a picture are kept apart on the hue and chroma axes rather than on lightness.
